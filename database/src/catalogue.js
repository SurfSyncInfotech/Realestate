const inr = new Intl.NumberFormat("en-IN");

export function formatPriceLabel(price, listingType) {
  const suffix = listingType === "sale" ? "" : " / month";
  if (price >= 10000000) return `₹${(price / 10000000).toFixed(2)} Cr${suffix}`;
  if (price >= 100000) return `₹${(price / 100000).toFixed(2)} L${suffix}`;
  return `₹${inr.format(price)}${suffix}`;
}

