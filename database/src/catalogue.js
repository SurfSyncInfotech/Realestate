// ---- query helpers (shared by the backend file fallback and the frontend) ----
export function searchCatalogue(items, filters = {}) {
  const { mode, city, query, type, maxPrice, sort = "featured" } = filters;
  let results = [...items];

  if (mode && mode !== "all") {
    if (mode === "luxury") results = results.filter((p) => p.luxury);
    else if (mode === "new-projects") results = results.filter((p) => p.newProject);
    else results = results.filter((p) => p.mode === mode);
  }
  const needle = (value) => value?.toString().trim().toLowerCase();
  const c = needle(city);
  if (c) results = results.filter((p) => `${p.city} ${p.location}`.toLowerCase().includes(c));
  const q = needle(query);
  if (q) {
    results = results.filter((p) =>
      [p.title, p.type, p.location, p.city, p.tag, p.description].join(" ").toLowerCase().includes(q),
    );
  }
  const t = needle(type);
  if (t) results = results.filter((p) => p.type.toLowerCase().includes(t));
  if (Number.isFinite(maxPrice)) results = results.filter((p) => p.price <= maxPrice);

  if (sort === "price-low") results.sort((a, b) => a.price - b.price);
  else if (sort === "price-high") results.sort((a, b) => b.price - a.price);
  return results;
}
